const DICTIONARIES: Record<Locale, Record<TranslationKey, string>> = { vi, en };

/** Tra chuỗi theo ngôn ngữ, thay các placeholder dạng `{name}`. */
export function translate(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const template = DICTIONARIES[locale]?.[key] ?? en[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/**
 * Ngôn ngữ hiện tại. Render phía server luôn dùng "vi" (giá trị mặc định của store) để HTML khớp
 * lần render đầu ở client — sau khi mount mới áp ngôn ngữ đã lưu trong localStorage, tránh
 * hydration mismatch mà không phải tắt hydrate cả store.
 */
export function useLocale(): Locale {
  const locale = useIntegrationStore((state) => state.locale);
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    setMounted(true);
  }, []);

  return mounted ? locale : "vi";
}

export function useT() {
  const locale = useLocale();
  return useCallback(
    (key: TranslationKey, vars?: Record<string, string | number>) => translate(locale, key, vars),
    [locale],
  );
}

